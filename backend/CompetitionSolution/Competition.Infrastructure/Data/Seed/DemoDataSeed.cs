    private static string Slug(string name) => SlugHelper.GenerateSlug(name);

    /// <summary>Slug lookup that tolerates hand-made duplicates or missing slugs (those tables have no unique slug index).</summary>
    private static Dictionary<string, T> BySlug<T>(IEnumerable<T> rows, Func<T, string?> slug) => rows
        .Where(x => !string.IsNullOrEmpty(slug(x)))
        .GroupBy(x => slug(x)!)
        .ToDictionary(g => g.Key, g => g.First());

    /// <summary>Part 1: countries, cities and stadiums (with coordinates), competition, seasons and rounds.</summary>
    public static async Task SeedGeographyAndCompetitionsAsync(AppDbContext db, CancellationToken cancellationToken = default)
    {
        var countries = BySlug(await db.Countries.ToListAsync(cancellationToken), x => x.Slug);
        foreach (var seed in Countries)
            if (!countries.ContainsKey(Slug(seed.Name)))
                db.Countries.Add(countries[Slug(seed.Name)] = new Country { Name = seed.Name, Slug = Slug(seed.Name) });

        var cities = BySlug(await db.Cities.ToListAsync(cancellationToken), x => x.Slug);
        foreach (var seed in Cities.Where(x => !cities.ContainsKey(Slug(x.Name))))
        {
            var geo = new GeoData { Latitude = seed.Lat, Longitude = seed.Lng, Description = seed.Name };
            db.GeoDatas.Add(geo);
            db.Cities.Add(cities[Slug(seed.Name)] = new City
            {
                Name = seed.Name, Slug = Slug(seed.Name), Population = seed.Population, IsCapital = seed.IsCapital,
                // The ids are `required` on City; EF fills them from the navigations on insert.
                Country = countries[Slug(seed.Country)], GeoData = geo, CountryId = default, GeoDataId = default,
            });
        }

        var stadiums = BySlug(await db.Stadiums.ToListAsync(cancellationToken), x => x.Slug);
        foreach (var seed in Stadiums.Where(x => !stadiums.ContainsKey(Slug(x.Name))))
        {
            var geo = new GeoData { Latitude = seed.Lat, Longitude = seed.Lng, Description = seed.Description };
            db.GeoDatas.Add(geo);
            db.Stadiums.Add(new Stadium
            {
                Name = seed.Name, Slug = Slug(seed.Name), Capacity = seed.Capacity,
                DateOfConstruction = new DateTime(seed.YearBuilt, 1, 1, 0, 0, 0, DateTimeKind.Utc),
                City = cities[Slug(seed.City)], GeoData = geo,
            });
        }

        var competition = await db.Competitions.FirstOrDefaultAsync(x => x.Slug == CompetitionSlug, cancellationToken);
        if (competition is null)
        {
            competition = new CompetitionEntity
            {
                Name = "Premijer liga BiH", Slug = CompetitionSlug, ShortName = "PLBiH",
                Description = "Top division of football in Bosnia and Herzegovina.",
                Country = countries[Slug("Bosnia and Herzegovina")],
            };
            db.Competitions.Add(competition);
        }

        foreach (var seed in Seasons)
        {
            var slug = Slug($"{competition.Slug} {seed.Name.Replace('/', ' ')}");
            var season = await db.Seasons.Include(x => x.Rounds).FirstOrDefaultAsync(x => x.Slug == slug, cancellationToken);
            if (season is null)
            {
                season = new Season
                {
                    Name = seed.Name, Slug = slug, StartDate = seed.Start, EndDate = seed.End,
                    IsCurrent = seed.IsCurrent, Competition = competition,
                };
                db.Seasons.Add(season);
            }
            for (var number = 1; number <= seed.Rounds; number++)
                if (season.Rounds.All(x => x.Number != number))
                    db.Rounds.Add(new Round
                    {
                        Name = $"Round {number}", Number = number, Season = season,
                        Slug = Slug($"{season.Slug} round {number}"),
                    });
        }

        await db.SaveChangesAsync(cancellationToken);
    }

    /// <summary>
    /// Minimal demo teams (club + first-team selection) so matches have opponents before the
    /// persons/selections seed (COMP-111) runs. That seed can enrich these rows by slug.
    /// </summary>
    public static async Task SeedDemoTeamsAsync(AppDbContext db, CancellationToken cancellationToken = default)
    {
        var bih = await db.Countries.FirstAsync(x => x.Slug == Slug("Bosnia and Herzegovina"), cancellationToken);
        var cities = BySlug(await db.Cities.ToListAsync(cancellationToken), x => x.Slug);
        var stadiums = BySlug(await db.Stadiums.ToListAsync(cancellationToken), x => x.Slug);
        var clubs = BySlug(await db.Clubs.ToListAsync(cancellationToken), x => x.Slug);
        // Selection slugs stay unique across soft-deleted rows (see the index in AppDbContext).
        var selectionSlugs = await db.Selections.IgnoreQueryFilters().Select(x => x.Slug).ToListAsync(cancellationToken);

        foreach (var seed in Teams)
        {
            var slug = Slug(seed.Name);
            var stadium = stadiums[Slug(seed.Stadium)];
            if (!clubs.TryGetValue(slug, out var club))
            {
                club = new Club
                {
                    Name = seed.Name, Slug = slug, FoundingDate = new LocalDate(seed.Founded, 1, 1),
                    ClubAge = ClubAge.Senior, City = cities[Slug(seed.City)], Stadium = stadium,
                };
                db.Clubs.Add(clubs[slug] = club);
            }
            if (!selectionSlugs.Contains(slug))
                db.Selections.Add(new Selection
                {
                    Name = seed.Name, Abbreviation = seed.Abbreviation, Slug = slug, Club = club,
                    Country = bih, HomeStadium = stadium,
                });
        }

        await db.SaveChangesAsync(cancellationToken);
    }

    /// <summary>
    /// Part 2: four matches per seeded round (round-robin). Rounds before <paramref name="now"/> are
    /// Finished with scores; later rounds are Scheduled, one of them Postponed. Rounds that already
    /// have matches are skipped, so a rerun never duplicates fixtures.
    /// </summary>
    public static async Task SeedMatchesAsync(AppDbContext db, Instant now, CancellationToken cancellationToken = default)
    {
        var names = Teams.Select(t => t.Name).ToArray();
        var found = await db.Selections.Where(x => names.Contains(x.Name)).ToListAsync(cancellationToken);
        var teams = Teams.Select(t => found.FirstOrDefault(x => x.Name == t.Name)).OfType<Selection>().ToList();
        if (teams.Count < 2) return;
        var fallbackStadiumId = (await db.Stadiums.OrderBy(x => x.Name).FirstAsync(cancellationToken)).Id;

        var statuses = await db.MatchStatuses.ToDictionaryAsync(x => x.Slug!, cancellationToken);
        var rounds = await db.Rounds.Include(x => x.Season)
            .Where(x => x.Season!.Competition!.Slug == CompetitionSlug && !x.Matches.Any())
            .OrderBy(x => x.Season!.StartDate).ThenBy(x => x.Number)
            .ToListAsync(cancellationToken);
        var usedSlugs = (await db.Matches.IgnoreQueryFilters().Select(x => x.Slug).ToListAsync(cancellationToken)).ToHashSet();
        var postponedSeeded = await db.Matches.AnyAsync(x => x.IsPostponed && x.Round!.Season!.Competition!.Slug == CompetitionSlug,
            cancellationToken);

        foreach (var round in rounds)
        {
            var kickOff = RoundKickOff(round, now);
            var pairs = RoundRobin(teams.Count, round.Number - 1);
            for (var i = 0; i < pairs.Count; i++)
            {
                var (home, away) = (teams[pairs[i].Home], teams[pairs[i].Away]);
                var date = kickOff.Plus(Duration.FromHours(2 * (i % 2)) + Duration.FromDays(i / 2));
                var finished = date < now;
                var postpone = !finished && !postponedSeeded;
                postponedSeeded |= postpone;
                var random = new Random(round.Season!.StartDate.Year * 1000 + round.Number * 10 + i);
                var match = new Match
                {
                    Date = date, RoundId = round.Id, StadiumId = home.HomeStadiumId ?? fallbackStadiumId,
                    HomeSelectionId = home.Id, AwaySelectionId = away.Id, IsPostponed = postpone,
                    FollowersCount = random.Next(50, 2500),
                    StatusId = statuses[finished ? "finished" : postpone ? "postponed" : "scheduled"].Id,
                    Slug = UniqueSlug($"{home.Slug} {away.Slug} {date.ToDateTimeUtc():yyyy-MM-dd}", usedSlugs),
                };
                if (finished)
                {
                    match.HomeScore = random.Next(0, 5);
                    match.AwayScore = random.Next(0, 4);
                    match.HalfHomeScore = random.Next(0, match.HomeScore.Value + 1);
                    match.HalfAwayScore = random.Next(0, match.AwayScore.Value + 1);
                }
                db.Matches.Add(match);
            }
        }

        await db.SaveChangesAsync(cancellationToken);
    }

    /// <summary>
    /// The current season's rounds are spread around <paramref name="now"/> (two thirds played, the rest upcoming)
    /// so the demo always has both results and fixtures. Other seasons use weekly dates from their start.
    /// </summary>
    private static Instant RoundKickOff(Round round, Instant now)
    {
        var season = round.Season!;
        if (!season.IsCurrent)
            return season.StartDate.PlusWeeks(round.Number - 1).At(new LocalTime(18, 0)).InUtc().ToInstant();
        var played = (int)Math.Ceiling(Seasons.First(x => x.IsCurrent).Rounds * 2 / 3.0);
        var day = now.InUtc().Date.PlusDays(7 * (round.Number - played) - 6);
        return day.At(new LocalTime(17, 0)).InUtc().ToInstant();
    }

    /// <summary>Circle method: team <c>count-1</c> stays fixed, the others rotate each round; home side alternates.</summary>
    public static IReadOnlyList<(int Home, int Away)> RoundRobin(int count, int roundIndex)
    {
        var even = count % 2 == 0 ? count : count + 1;
        var rotating = Enumerable.Range(0, even - 1).Select(i => (i + roundIndex) % (even - 1)).ToList();
        var order = new List<int> { even - 1 };
        order.AddRange(rotating);
        var pairs = new List<(int, int)>();
        for (var i = 0; i < even / 2; i++)
        {
            var (a, b) = (order[i], order[even - 1 - i]);
            if (a >= count || b >= count) continue;
            pairs.Add(roundIndex % 2 == 0 ? (a, b) : (b, a));
        }
        return pairs;
    }

    private static string UniqueSlug(string text, HashSet<string?> used)
    {
        var slug = Slug(text);
        for (var i = 2; !used.Add(slug); i++)
            slug = $"{Slug(text)}-{i}";
        return slug;
    }
